MAP_W = 96
MAP_H = 40

# Índices de pixels que pertencem ao "olho esquerdo" e "olho direito"
# (região do lilás claro — índice 5 na paleta) para animação de brilho.
# Detectados no pixel map: linha 8–14 col ~37–43 (esq) e ~50–58 (dir).

EYE_COLOR_IDX = 5  # lilás claro
EYE_GLOW_COLOR = (200, 140, 220)  # lilás mais brilhante para o glow


# ---------------------------------------------------------------------------
# Config de exibição
# ---------------------------------------------------------------------------

PIXEL_SIZE = 12  # tamanho de cada "pixel" em tela
WIN_W = MAP_W * PIXEL_SIZE
WIN_H = MAP_H * PIXEL_SIZE
FPS = 60
TITLE = "Boss — Gosma"

BG_COLOR = (0, 0, 0)


# ---------------------------------------------------------------------------
# Helpers de animação
# ---------------------------------------------------------------------------


def lerp_color(a: tuple, b: tuple, t: float) -> tuple:
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


def brighten(color: tuple, factor: float) -> tuple:
    return tuple(min(255, int(c * factor)) for c in color)


# ---------------------------------------------------------------------------
# Renderer principal
# ---------------------------------------------------------------------------


class BossRenderer:
    def __init__(self, surface: pygame.Surface) -> None:
        self.surface = surface
        self.time = 0.0

        # Pré-cria surfaces de pixel (1x1 escaladas) como rects para blit
        # Na verdade, apenas blit rects coloridos diretamente — mais rápido.
        self._pixel_surf_cache: dict[tuple, pygame.Surface] = {}

    # --------------------------------------------------------------- rendering
    def _get_pixel_surf(self, color: tuple) -> pygame.Surface:
        if color not in self._pixel_surf_cache:
            s = pygame.Surface((PIXEL_SIZE, PIXEL_SIZE))
            s.fill(color)
            self._pixel_surf_cache[color] = s
        return self._pixel_surf_cache[color]

    def render(self, dt: float) -> None:
        self.time += dt

        t = self.time
        # Pulsação suave do corpo inteiro (escala via offset de cor)
        pulse = (math.sin(t * 1.4) + 1.0) / 2.0  # 0..1
        # Brilho dos olhos
        eye_pulse = (math.sin(t * 2.2) + 1.0) / 2.0

        # Wave horizontal leve (deslocamento de coluna por linha)
        def wave_offset(row: int) -> float:
            return math.sin(t * 1.1 + row * 0.35) * 0.6  # subpixel

        self.surface.fill(BG_COLOR)

        for row_i, row in enumerate(PIXEL_MAP):
            y = row_i * PIXEL_SIZE
            dx = wave_offset(row_i)

            for col_i, color_idx in enumerate(row):
                base_color = PALETTE[color_idx]

                # Escurece/clareia o corpo com o pulso
                if color_idx not in (14, 13, 15, 12):  # não anima os pretos puros
                    factor = 0.85 + 0.30 * pulse
                    draw_color = brighten(base_color, factor)
                else:
                    draw_color = base_color

                # Sobrepõe brilho nos olhos
                if color_idx == EYE_COLOR_IDX:
                    draw_color = lerp_color(
                        PALETTE[EYE_COLOR_IDX], EYE_GLOW_COLOR, eye_pulse
                    )
                    draw_color = brighten(draw_color, 1.0 + 0.5 * eye_pulse)

                x = col_i * PIXEL_SIZE + int(dx)

                # Só renderiza se não for fundo puro
                if color_idx == 14 and row_i > MAP_H - 4:
                    continue

                pygame.draw.rect(
                    self.surface, draw_color, (x, y, PIXEL_SIZE, PIXEL_SIZE)
                )


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def main() -> None:
    pygame.init()
    screen = pygame.display.set_mode((WIN_W, WIN_H))
    pygame.display.set_caption(TITLE)
    clock = pygame.time.Clock()

    renderer = BossRenderer(screen)

    running = True
    while running:
        dt = min(clock.tick(FPS) / 1000.0, 0.05)

        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                running = False
            elif event.type == pygame.KEYDOWN:
                if event.key == pygame.K_ESCAPE:
                    running = False
                elif event.key == pygame.K_s:
                    pygame.image.save(screen, "slime_boss.png")
                    print("Salvo: slime_boss.png")

        renderer.render(dt)
        pygame.display.flip()

    pygame.quit()
    sys.exit()


if __name__ == "__main__":
    main()
